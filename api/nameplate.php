/**
 * Шильдик → аналог → письмо клиенту.
 *
 * Конвейер: фото шильдика распознаёт модель ИИ (это она умеет), но:
 *   1. Читает НЕ одну версию, а три гипотезы с уверенностью по каждой — на потёртом
 *      шильдике «R 97» и «R 87» отличаются одним штрихом, и одна версия скрывает риск.
 *   2. Соответствие «оригинал → ZR» подставляет справочник, а не модель
 *      (analog_lookup: analogs.csv + analog_codes.csv + карточки сайта, 20 марок).
 *   3. Цена и срок берутся из прайса (api/price.php). Нет прайса — в письме
 *      честно «уточнит инженер», а не выдуманное число.
 *   4. Пока распознавание не подтверждено человеком, письмо клиенту НЕ уходит:
 *      статус лида review, черновик лежит в карточке.
 *
 * Используется автопилотом (ai_auto.php) и кнопкой «Черновик» в карточке лида.
 */

require_once __DIR__ . '/helpers.php';
require_once __DIR__ . '/price.php';
require_once __DIR__ . '/site_kb.php';

/**
 * Системный промпт распознавания шильдика: три гипотезы вместо одной.
 * Цены и сроки модель не называет — они приходят из прайса уже после подбора.
 */
function nameplate_system(): string {
    return "Ты — инженер-подборщик редукторов завода «Завод Редукторов». "
        . "На фото или в тексте — шильдик (табличка) привода. Прочитай его.\n\n"
        . "ГЛАВНОЕ: дай ТРИ версии прочтения модели, а не одну. Шильдики бывают потёртые, "
        . "залитые маслом, снятые под углом; «R 97» и «R 87» отличаются одним штрихом. "
        . "Версии упорядочь по убыванию уверенности.\n\n"
        . "Верни СТРОГО валидный JSON без markdown:\n"
        . '{'
        . '"hypotheses":[{"brand":"производитель","model":"модель как на шильдике","confidence":0,"why":"по каким символам решил"}],'
        . '"params":{"kw":"","rpm_in":"","rpm_out":"","ratio":"","torque_nm":"","mount":"лапы|фланец|насадной|—","serial":"","year":""},'
        . '"readable":"что видно на шильдике дословно, строкой",'
        . '"qty":1,'
        . '"missing":["чего не хватает для точного подбора"]'
        . "}\n\n"
        . "Правила: не выдумывай символы, которых не видишь — лучше пустая строка. "
        . "Цену, срок и наличие НЕ называй вообще. Российский аналог сам не подбирай: "
        . "соответствие подставит справочник завода.\n";
}

/**
 * Подбор по гипотезам: для каждой ищем ZR в справочнике.
 * Возвращает список [{brand, model, confidence, zr, type, kw_range, verified, source}].
 */
function nameplate_match(array $hypotheses): array {
    $out = [];
    foreach ($hypotheses as $h) {
        $brand = trim((string)($h['brand'] ?? ''));
        $model = trim((string)($h['model'] ?? ''));
        $query = trim($brand . ' ' . $model);
        if ($query === '') continue;

        $hit = analog_lookup($query);                 // analogs.csv + коды + карточки сайта
        $site = site_lookup_models($query, 1);        // тип и диапазон мощности для письма
        // На шильдике серия часто с буквами исполнения: STM «OMP 90» = серия O, типоразмер 90
        // (MP — под мотор). Нет точного совпадения — отбрасываем буквы справа: OMP → OM → O.
        $via = '';
        if (!$hit && preg_match('~^([A-Za-zА-Яа-я]{2,5})\s*-?\s*(\d{2,4})\b~u', $model, $mm)) {
            for ($k = mb_strlen($mm[1]) - 1; $k >= 1 && !$hit; $k--) {
                $try = trim($brand . ' ' . mb_substr($mm[1], 0, $k) . ' ' . $mm[2]);
                $h2 = analog_lookup($try);
                if ($h2) { $hit = $h2; $via = $try; $site = site_lookup_models($try, 1) ?: $site; }
            }
        }
        $row = [
            'brand'      => $brand,
            'model'      => $model,
            'confidence' => (int)($h['confidence'] ?? 0),
            'why'        => (string)($h['why'] ?? ''),
            'zr'         => $hit['zr'] ?? '',
            'type'       => $hit['category'] ?? ($site[0]['type'] ?? ''),
            'kw_range'   => $site[0]['kw'] ?? '',   // ключ справочника называется kw
            'verified'   => (bool)$hit,
            'source'     => ($hit['source'] ?? 'нет в справочнике') . ($via !== '' ? ' (по серии: ' . $via . ')' : ''),
        ];
        $row['price_text'] = $row['zr'] !== '' ? price_text($row['zr']) : '';
        $out[] = $row;
    }
    // сначала подтверждённые справочником, затем по уверенности прочтения
    usort($out, static fn($a, $b) => [$b['verified'], $b['confidence']] <=> [$a['verified'], $a['confidence']]);
    return $out;
}

/**
 * Черновик письма клиенту по результату подбора.
 *
 * $matched — результат nameplate_match(), $params — распознанные характеристики.
 * Письмо не отправляется отсюда: его показывают инженеру, он подтверждает.
 */
function nameplate_draft(array $matched, array $params = [], int $qty = 1): string {
    $best = $matched[0] ?? null;
    $lines = ['Здравствуйте!', ''];

    if (!$best || !$best['verified']) {
        $seen = $best ? trim($best['brand'] . ' ' . $best['model']) : '';
        $lines[] = $seen !== ''
            ? "По фото шильдика читается $seen, но подтвердить замену по справочнику сходу не получилось — "
              . "угадывать не буду. Передал инженеру: он сверит по чертежу и пришлёт точное соответствие."
            : "Фото получили, но шильдик читается неуверенно. Пришлите, пожалуйста, снимок ближе и без бликов "
              . "или продиктуйте модель — подберём замену.";
        $lines[] = '';
        $lines[] = 'Чтобы ускорить подбор, пригодятся: мощность двигателя, обороты на выходе, '
                 . 'способ крепления (лапы, фланец, насадной) и количество.';
        $lines[] = '';
        $lines[] = 'С уважением,';
        $lines[] = 'Завод Редукторов, +7 (495) 151-41-02';
        return implode("\n", $lines);
    }

    $orig = trim($best['brand'] . ' ' . $best['model']);
    $lines[] = "С шильдика читаю: $orig" . ($best['type'] !== '' ? " ({$best['type']})" : '') . '.';

    $p = [];
    foreach ([
        'kw' => 'мощность %s кВт', 'ratio' => 'передаточное %s',
        'rpm_out' => 'обороты на выходе %s об/мин', 'torque_nm' => 'момент %s Н·м',
        'mount' => 'крепление: %s',
    ] as $k => $fmt) {
        $v = trim((string)($params[$k] ?? ''));
        if ($v !== '' && $v !== '—') $p[] = sprintf($fmt, $v);
    }
    if ($p) $lines[] = 'Характеристики: ' . implode(', ', $p) . '.';

    $lines[] = '';
    $lines[] = "Прямая замена нашего производства — {$best['zr']}. "
             . 'Повторяет присоединительные и габаритные размеры, встаёт на существующие болты, '
             . 'гарантия 36 месяцев, паспорт на изделие.';

    $priceLine = $best['price_text'];
    if ($priceLine !== '' && $priceLine !== 'цену и срок подтвердит инженер') {
        $lines[] = ($qty > 1 ? "Цена за штуку: $priceLine. Количество: $qty шт." : "Цена: $priceLine.");
    } else {
        $lines[] = 'Цену и срок инженер посчитает под ваш типоразмер и количество и пришлёт следом — '
                 . 'это в течение дня. Оригинал под заказ тоже посчитаем, если нужно сравнить.';
    }

    if (count($matched) > 1) {
        $alt = [];
        foreach (array_slice($matched, 1, 2) as $m) {
            // молчим о версиях, которые ведут к тому же ZR: для клиента это одна и та же замена
            if ($m['verified'] && $m['zr'] !== $best['zr']) {
                $alt[] = trim($m['brand'] . ' ' . $m['model']) . ' → ' . $m['zr'];
            }
        }
        if ($alt) {
            $lines[] = '';
            $lines[] = 'На фото возможны и другие прочтения: ' . implode('; ', $alt) . '. '
                     . 'Подтвердите, пожалуйста, модель — или пришлите фото шильдика крупнее, чтобы не ошибиться.';
        }
    }

    $lines[] = '';
    $lines[] = 'Если пришлёте фото узла или чертёж присоединительных размеров — сверим посадочные места '
             . 'и подтвердим, что редуктор встанет без переделки рамы.';
    $lines[] = '';
    $lines[] = 'С уважением,';
    $lines[] = 'Завод Редукторов, +7 (495) 151-41-02';
    return implode("\n", $lines);
}

/**
 * Готов ли результат к автоотправке клиенту.
 * Требуем: уверенное прочтение, подтверждённый справочником ZR, отсутствие пробелов
 * и заметный отрыв первой гипотезы от второй — иначе решает человек.
 */
function nameplate_can_autosend(array $matched, array $missing = [], int $minConfidence = 80): bool {
    if (!$matched || !empty($missing)) return false;
    $best = $matched[0];
    if (empty($best['verified']) || $best['confidence'] < $minConfidence) return false;
    if (isset($matched[1]) && !empty($matched[1]['verified']) && $matched[1]['zr'] !== $best['zr']) {
        // две подтверждённые версии ведут к РАЗНЫМ ZR и уверенность близка —
        // риск отправить клиенту не тот редуктор, решает человек
        if ($best['confidence'] - (int)$matched[1]['confidence'] < 20) return false;
    }
    return true;
}
