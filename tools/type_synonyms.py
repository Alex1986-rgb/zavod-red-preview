        ('<h2 style="font-size:26px">Типоразмеры и характеристики плоских мотор-редукторов</h2>',
         '<h2 style="font-size:26px">Типоразмеры и характеристики параллельно-осевых (плоских) мотор-редукторов</h2>'),
