#!/usr/bin/env python3
"""Чинит падежи названий типов редукторов в уже опубликованных текстах.

Зачем: генератор статей по типам строил родительный падеж наивно — приписывал «а»
к названию типа. В результате в заголовках и текстах живых страниц стоит «КПД червячный
редуктора», «Монтажные положения соосно-цилиндрический редуктора», «Замена импортного
цилиндрический редуктор». В заголовке сравнения второй тип стоял в творительном падеже
вместо именительного: «Червячный редуктор или цилиндрическим: что выбрать».

Сам шаблон исправлен (поле gen в tools/gen_type_articles.py), но существующие файлы
перезаписывать генератором нельзя: --rebuild собирает статью заново и теряет
тематический hero и og:image, проставленные отдельным проходом. Поэтому правка
точечная — меняются только сломанные формы, остальное содержимое не трогается.

Порядок замен важен: составные типы («плоский цилиндрический») идут раньше простых,
иначе «цилиндрический» съест их часть.

Скрипт идемпотентен: повторный запуск ничего не меняет.

Запуск:  python3 tools/fix_type_genitive.py [--dry]
"""
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRY = '--dry' in sys.argv

# (именительный, родительный) — от составных к простым
TYPES = [
    ('плоский цилиндрический', 'плоского цилиндрического'),
    ('соосно-цилиндрический', 'соосно-цилиндрического'),
    ('коническо-цилиндрический', 'коническо-цилиндрического'),
    ('цилиндро-конический', 'цилиндро-конического'),
    ('червячный', 'червячного'),
    ('планетарный', 'планетарного'),
    ('цилиндрический', 'цилиндрического'),
]

# заголовок сравнения: второй тип должен стоять в именительном падеже
COMPARE = [
    ('или цилиндрическим:', 'или цилиндрический:'),
    ('или червячным:', 'или червячный:'),
    ('или соосным:', 'или соосный:'),
]

RULES = []
for nom, gen in TYPES:
    RULES.append((f'импортного {nom} редуктор', f'импортного {gen} редуктора'))
for nom, gen in TYPES:
    RULES.append((f'{nom} редуктора', f'{gen} редуктора'))
RULES += COMPARE

SECTIONS = ('blog', 'catalog', 'glossary', 'otrasli', 'cases', 'uslugi', 'brands')


def main():
    pages = []
    for sec in SECTIONS:
        pages += glob.glob(os.path.join(ROOT, sec, '*.html'))
    pages += glob.glob(os.path.join(ROOT, '*.html'))

    changed = total = 0
    for path in pages:
        with open(path, encoding='utf-8', errors='ignore') as f:
            text = f.read()
        new = text
        n = 0
        for old, repl in RULES:
            cnt = new.count(old)
            if cnt:
                new = new.replace(old, repl)
                n += cnt
        if not n:
            continue
        changed += 1
        total += n
        if not DRY:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(new)

    print(f'страниц просмотрено: {len(pages)}')
    print(f'{"будет исправлено" if DRY else "исправлено"}: файлов {changed}, форм {total}')


if __name__ == '__main__':
    main()
