def main():
    if "--check" in sys.argv:
        W, H = 430, 287
        names = sorted(QUADS)
        sheet = Image.new("RGB", (W * 2, H * ((len(names) + 1) // 2)),
                          (255, 255, 255))
        for i, n in enumerate(names):
            p = os.path.join(RAW, n + ".png")
            if not os.path.isfile(p):
                continue
            im = Image.open(p).convert("RGB").resize((W, H), Image.LANCZOS)
            d = ImageDraw.Draw(im)
            for kind, col in (("plate", (255, 40, 40)), ("doc", (0, 230, 0))):
                q = QUADS[n][kind]
                if not q:
                    continue
                pts = [(x * W, y * H) for x, y in q]
                d.line(pts + [pts[0]], fill=col, width=3)
            d.text((6, 6), n, fill=(255, 255, 0))
            sheet.paste(im, ((i % 2) * W, (i // 2) * H))
        sheet.save(os.path.join(HERE, "frames_check.png"))
        print("frames_check.png")

    os.makedirs(os.path.join(HERE, "batch"), exist_ok=True)
    json.dump(QUADS, open(os.path.join(HERE, "batch", "quads.json"), "w"),
              ensure_ascii=False, indent=1)
    print(f"площадок размечено: {len(QUADS)} кадров")


if __name__ == "__main__":
    main()
