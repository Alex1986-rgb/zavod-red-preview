def our_type(row_text):
    low = row_text.lower()
    for key, name, link in TYPE_MAP:
        if key in low:
            return name, link
    return "редукторы ZR соответствующего типа", "/catalog/"


def load_series():
    data = {}
    for slug in BRANDS:
        p = os.path.join(BASE, "brands", f"{slug}.html")
        rows = []
        if os.path.isfile(p):
            t = open(p, encoding="utf-8").read()
            for a, b in re.findall(r"<tr><td>([^<]{1,60})</td><td>(?:<b>)?([^<]{1,90})", t):
                name, link = our_type(a + " " + b)
                rows.append({"series": a.strip(), "desc": b.strip(), "zr": name, "link": link})
        data[slug] = rows[:7]
    return data


# ---------------------------------------------------------------- шаблон
def esc(s):
    return s.replace("&", "&amp;").replace('"', "&quot;")


def xref_table(rows, brand):
    if not rows:
        return ""
    trs = "\n".join(
        f"      <tr><td>{r['series']}</td><td><b><a href=\"{r['link']}\">{r['zr']}</a></b></td></tr>"
        for r in rows
    )
    return (f'<table class="xref">\n    <thead><tr><th>Серия {brand}</th><th>Наша замена</th></tr></thead>'
            f'\n    <tbody>\n{trs}\n    </tbody>\n  </table>')


def faq_html(faq):
    items = "\n".join(
        f"      <details><summary>{q}</summary><div>{a}</div></details>" for q, a in faq
    )
    return f'<div class="faq-grid">\n    <div class="cat-faq">\n{items}\n    </div>'


def faq_ld(faq):
    ent = [{"@type": "Question", "name": q,
            "acceptedAnswer": {"@type": "Answer", "text": re.sub("<[^>]+>", "", a)}} for q, a in faq]
    return json.dumps({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": ent},
                      ensure_ascii=False)


def article_ld(title, desc, url):
    return json.dumps({"@context": "https://schema.org", "@type": "Article", "headline": title,
                       "description": desc, "image": f"{SITE}/og-image.jpg",
                       "author": {"@type": "Organization", "areaServed": "RU", "name": "Завод Редукторов"},
                       "publisher": {"@type": "Organization", "areaServed": "RU", "name": "Завод Редукторов",
                                     "logo": {"@type": "ImageObject", "url": f"{SITE}/assets/zr_logo.webp"}},
                       "mainEntityOfPage": url}, ensure_ascii=False)


def crumbs_ld(short, url):
    return json.dumps({"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "Главная", "item": f"{SITE}/"},
        {"@type": "ListItem", "position": 2, "name": "Блог", "item": f"{SITE}/blog/"},
        {"@type": "ListItem", "position": 3, "name": short, "item": url}]}, ensure_ascii=False)


class Skeleton:
    def __init__(self):
        t = open(SKELETON, encoding="utf-8").read()
        i = t.find('<div class="art">')
        j = t.find("</div></div></section>", i)
        self.head_body = t[:i]
        k = t.find('<div class="faq-grid">', j)
        m = t.find("\n  </div>\n</div></section>", k)
        self.mid = t[j:k]
        self.tail = t[m:]

    def render(self, slug, title, desc, h1, eyebrow, short, art, faq, minutes):
        url = f"{SITE}/blog/{slug}"
        hb = self.head_body
        hb = re.sub(r"<title>[^<]*</title>", f"<title>{title}</title>", hb)
        hb = re.sub(r'(<meta name="description" content=")[^"]*', r"\g<1>" + esc(desc), hb)
        hb = re.sub(r'(<link rel="canonical" href=")[^"]*', r"\g<1>" + url, hb)
        hb = re.sub(r'(<meta property="og:url" content=")[^"]*', r"\g<1>" + url, hb)
        hb = re.sub(r'(<meta property="og:title" content=")[^"]*', r"\g<1>" + esc(title), hb)
        hb = re.sub(r'(<meta property="og:description" content=")[^"]*', r"\g<1>" + esc(desc), hb)
        lds = [article_ld(title, desc, url), crumbs_ld(short, url), faq_ld(faq)]
        parts = hb.split('<script type="application/ld+json">')
        hb = parts[0] + "".join(
            f'<script type="application/ld+json">{ld}</script>\n' for ld in lds)
        hb += "</head>\n<body>\n" + self._chrome()
        hb += (f'\n<div class="wrap crumbs"><a href="/">Главная</a><span>›</span>'
               f'<a href="/blog/">Блог</a><span>›</span>{short}</div>\n'
               f'<section class="phero"><div class="wrap">\n  <div class="eyebrow">{eyebrow}</div>\n'
               f"  <h1>{h1}</h1>\n"
               f'  <p class="art-meta">Опыт инженеров Завода Редукторов · время чтения ~{minutes} минут</p>\n'
               f"</div></section>\n\n"
               f'<section class="section" style="padding-top:40px"><div class="wrap"><div class="art">\n')
        return hb + art + "\n" + self.mid + faq_html(faq) + self.tail

    def _chrome(self):
        t = open(SKELETON, encoding="utf-8").read()
        a = t.find("<header")
        b = t.find("</header>") + len("</header>")
        return t[a:b]


