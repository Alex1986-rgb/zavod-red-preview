def series_para(p, series):
    """Место исполнения внутри своей серии. Меняется у каждой карточки, поэтому разводит
    соседей, которых диапазоны не различают, и заодно помогает выбрать."""
    lo, hi, rank, total = series
    if total < 2:
        return ''
    place = ORD[rank] if rank < len(ORD) else f'{rank + 1}-е по мощности'
    out_kw = p['kw'] * 0.95
    return (f'<p>В серии с передаточным числом {p["ratio"]} у этой модели '
            f'{total} исполнений — от {lo} до {hi} кВт; данное {place}. '
            f'На выходном валу при КПД около 0,95 остаётся примерно {ru(out_kw, 2)} кВт. '
            f'Если требуемый момент машины близок к {p["torque"]} Н·м, берут соседнее '
            f'исполнение с запасом, а не это впритык.</p>')


def build_series():
    """(модель, редукция) → мощности по возрастанию. Читаем только начало файлов."""
    import collections as _c
    groups = _c.defaultdict(list)
    for path in sorted(glob.glob(os.path.join(ANALOG, '*.html'))):
        head = open(path, encoding='utf-8', errors='ignore').read(4000)
        d = DESC.search(head)
        if not d:
            continue
        m = PARAMS.search(d.group(1))
        t = re.search(r'Редуктор ([^(]+)\(', d.group(1))
        if not m or not t:
            continue
        groups[(t.group(1).strip(), m.group('ratio'))].append(m.group('power'))
    for k in groups:
        groups[k] = sorted(set(groups[k]), key=num)
    return groups


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry', action='store_true')
    ap.add_argument('--brand')
    ap.add_argument('--limit', type=int)
    args = ap.parse_args()

    series_idx = build_series()
    files = sorted(glob.glob(os.path.join(ANALOG, '*.html')))
    if args.brand:
        files = [f for f in files if os.path.basename(f).startswith(args.brand + '-')]
    if args.limit:
        files = files[:args.limit]

    changed = no_params = fixed_broken = apps_done = 0
    for path in files:
        if os.path.basename(path) == 'index.html':
            continue
        with open(path, encoding='utf-8', errors='ignore') as f:
            text = f.read()
        d = DESC.search(text)
        m = PARAMS.search(d.group(1)) if d else None
        if not m:
            no_params += 1
            continue
        p = {
            'power': m.group('power'), 'torque': m.group('torque'),
            'ratio': m.group('ratio'), 'rpm': m.group('rpm'),
            'kw': num(m.group('power')), 'rpm_num': num(m.group('rpm')),
            'torque_num': num(m.group('torque')),
        }

        new = BLOCK.sub('', text)

        # 1. абзац «Это исполнение» + место в серии
        if ANCHOR in new:
            t = re.search(r'Редуктор ([^(]+)\(', d.group(1))
            key = (t.group(1).strip(), p['ratio']) if t else None
            powers = series_idx.get(key, [])
            extra = ''
            if p['power'] in powers:
                extra = series_para(p, (powers[0], powers[-1],
                                        powers.index(p['power']), len(powers)))
            new = new.replace(ANCHOR, paragraph(p, extra) + ANCHOR, 1)

        # 2. список применения — по диапазонам оборотов и мощности
        after = APPS.sub(lambda mm: mm.group(1) + apps_html(p) + mm.group(3), new, count=1)
        if after != new:
            apps_done += 1
        new = after

        # 3. склеенные передаточное и момент
        if BROKEN.search(new):
            new = BROKEN.sub(
                f'требуемому моменту — у этого исполнения {p["torque"]} Н·м '
                f'при {p["rpm"]} об/мин на выходном валу', new)
            fixed_broken += 1

        if new == text:
            continue
        changed += 1
        if not args.dry:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(new)

    print(f'просмотрено файлов: {len(files)}')
    print(f'{"будет изменено" if args.dry else "изменено"}: {changed}')
    print(f'   список применения подобран: {apps_done}')
    print(f'   исправлена склейка «моменту до i, Н·м»: {fixed_broken}')
    print(f'   без параметров в описании (пропущены): {no_params}')


if __name__ == '__main__':
    main()
