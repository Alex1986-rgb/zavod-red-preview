ANCHOR = '<h3>Применение</h3>'


def num(s):
    return float(s.replace(',', '.'))


def ru(x, nd=0):
    """Число по-русски: запятая вместо точки, без хвостовых нулей."""
    s = f'{x:.{nd}f}'
    return s.replace('.', ',')


def speed_band(rpm):
    if rpm < 15:
        return 'ultra'
    if rpm < 40:
        return 'slow'
    if rpm < 100:
        return 'mid'
    if rpm < 300:
        return 'fast'
    return 'direct'


def power_band(kw):
    if kw <= 0.18:
        return 'micro'
    if kw <= 0.37:
        return 'light'
    if kw <= 1.1:
        return 'norm'
    if kw <= 3:
        return 'mid'
    if kw <= 7.5:
        return 'heavy'
    return 'xheavy'


def torque_band(t):
    """Момент у соседей по серии разный — это и есть главный разделитель текста
    внутри одной редукции, где обороты совпадают."""
    if t < 50:
        return 't1'
    if t < 200:
        return 't2'
    if t < 800:
        return 't3'
    if t < 3000:
        return 't4'
    return 't5'


