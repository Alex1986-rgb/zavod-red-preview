#!/usr/bin/env python3
"""Разводит тексты карточек /analog/ внутри одной серии: они совпадали на 99,9 %.

Зачем: у шести карточек одной модели с разной мощностью весь текст, 8 458 знаков, совпадал
буквально — различались пять слов: мощность и момент. Яндекс исключает такие страницы с
пометкой «малоценная», в поиске держится около 4 600 адресов из 95 068.

Разводим НЕ синонимами, а фактами самой карточки. У каждой на странице уже есть свои
мощность, момент, передаточное число и обороты на выходном валу. От оборотов зависит, для
чего исполнение годится: 9 об/мин и 370 об/мин — это разные машины, и писать про них одно
и то же неправильно по существу, а не только для поиска.

Что делается на каждой карточке:
  1. Абзац «Это исполнение» — обороты, время одного оборота вала, к чему такая скорость
     пригодна, на что смотреть при подборе. Формулировки выбираются по диапазону оборотов
     и мощности, числа берутся со страницы.
  2. Список «Применение» — вместо общего на все 73 899 карточек подбирается по тем же
     диапазонам: тихоходному исполнению незачем числиться в насосах, быстроходному — в
     шнековых питателях.
  3. Чинится фраза «требуемому моменту до 28,83, 150 Н·м»: в шаблон подставили подряд
     передаточное и момент, и получилось, что момент измеряется передаточным числом.
     Встречается на 69 203 карточках.

Ничего не выдумывается: всё, что пишется, либо взято со страницы, либо арифметика от неё.

Скрипт идемпотентен: абзац помечен маркером и при повторном запуске заменяется.

Запуск:  python3 tools/analog_vary_text.py [--dry] [--brand bauer] [--limit N]
"""
