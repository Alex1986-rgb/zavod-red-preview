def brand_table(series, key):
    """Таблица: бренд → серии данного типа."""
    rows = []
    for slug, (bname, _) in BRANDS.items():
        found = [r["series"] for r in series.get(slug, []) if key in (r["series"] + " " + r["desc"]).lower()]
        if found:
            rows.append((bname, slug, ", ".join(found[:3])))
    if not rows:
        return "", []
    trs = "\n".join(
        f'      <tr><td><a href="/brands/{s}">{b}</a></td><td><b>{ser}</b></td></tr>'
        for b, s, ser in rows[:12])
    tbl = (f'<table class="xref">\n    <thead><tr><th>Бренд</th><th>Серии этого типа</th></tr></thead>'
           f'\n    <tbody>\n{trs}\n    </tbody>\n  </table>')
    return tbl, rows


